# Generates the voice-over lines with Piper (Indonesian voice) and writes vo-data.js with durations.
# usage: python3 tools-vo.py <model.onnx>
import sys, json, subprocess, wave, os
model = sys.argv[1]
# id, spoken text (TTS spelling), subtitle text (display)
LINES = [(l["id"], l["spoken"], l["text"]) for l in json.load(open("lines.json"))]
os.makedirs("assets/vo", exist_ok=True)
out = []
only = set(sys.argv[2:])
for i, spoken, sub in LINES:
    if only and i not in only: continue
    f = f"assets/vo/{i}.wav"
    subprocess.run([sys.executable, "-m", "piper", "-m", model, "-f", f, "--length-scale", "1.08", "--sentence-silence", "0"], input=spoken.encode(), check=True, capture_output=True)
    # trim leading/trailing silence
    t = f + ".t.wav"
    subprocess.run(["ffmpeg","-v","error","-y","-i",f,"-af","silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.05",t],check=True)
    os.replace(t, f)
    with wave.open(f) as w: d = w.getnframes()/w.getframerate()
    out.append({"id": i, "text": sub, "file": f, "dur": round(d, 3)})
    print(i, round(d,2))
old = {}
try:
    import re
    old = {l["id"]: l for l in json.loads(re.search(r"VO_LINES=(\[.*?\]);", open("vo-data.js").read(), re.S).group(1))}
except Exception: pass
for i, spoken, sub in LINES:
    if not any(o["id"] == i for o in out):
        f = f"assets/vo/{i}.wav"
        with wave.open(f) as w: d = w.getnframes()/w.getframerate()
        out.append({"id": i, "text": sub, "file": f, "dur": round(d, 3)})
order = [l[0] for l in LINES]
out.sort(key=lambda o: order.index(o["id"]))
js = "// generated by tools-vo.py\n(function(){const VO_LINES=" + json.dumps(out, ensure_ascii=False, indent=0) + ";\nif (typeof module!=='undefined') module.exports=VO_LINES; else globalThis.VO_LINES=VO_LINES;})();\n"
open("vo-data.js","w").write(js)
print("total", sum(o["dur"] for o in out))
