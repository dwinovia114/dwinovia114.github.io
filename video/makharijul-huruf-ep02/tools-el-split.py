# Splits per-scene ElevenLabs takes (assets/el/sN.mp3, lines separated by [long pause]) into
# per-line files assets/vo/<id>.wav, then rewrites vo-data.js with the new durations.
# usage: python3 tools-el-split.py            (processes every assets/el/sN.mp3 that exists)
# A scene whose pause count does not match its line count is skipped with a warning.
import subprocess, re, json, os, wave, sys
SCENES = {}
for l in json.load(open("lines.json")): SCENES.setdefault(l["scene"], []).append(l["id"])
def silences(f, d):
    r = subprocess.run(["ffmpeg","-hide_banner","-i",f,"-af",f"silencedetect=noise=-40dB:d={d}","-f","null","-"],capture_output=True,text=True).stderr
    st = [float(x) for x in re.findall(r"silence_start: ([0-9.]+)", r)]
    en = [float(x) for x in re.findall(r"silence_end: ([0-9.]+)", r)]
    return [(s, e) for s, e in zip(st, en) if s > 0.05]
def dur(f):
    with wave.open(f) as w: return w.getnframes() / w.getframerate()
for sc, ids in SCENES.items():
    src = f"assets/el/{sc}.mp3"
    if not os.path.exists(src): continue
    sil = None
    for d in (0.45, 0.6, 0.8, 0.35, 1.0):
        s = silences(src, d)
        if len(s) == len(ids) - 1: sil = s; break
    if sil is None: print(f"!! {sc}: could not find {len(ids)-1} pauses, skipped"); continue
    cuts = [0] + [(a + b) / 2 for a, b in sil] + [None]
    for i, lid in enumerate(ids):
        out = f"assets/vo/{lid}.wav"
        args = ["ffmpeg","-v","error","-y","-i",src,"-ss",str(cuts[i])] + (["-to",str(cuts[i+1])] if cuts[i+1] else [])
        args += ["-af","silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.05","-ar","48000","-ac","1",out]
        subprocess.run(args, check=True)
        print(sc, lid, round(dur(out), 2))
# refresh durations in vo-data.js
txt = open("vo-data.js").read()
data = json.loads(re.search(r"VO_LINES=(\[.*?\]);", txt, re.S).group(1))
for l in data: l["dur"] = round(dur(l["file"]), 3)
open("vo-data.js","w").write("// generated by tools-vo.py / tools-el-split.py\n(function(){const VO_LINES=" + json.dumps(data, ensure_ascii=False, indent=0) + ";\nif (typeof module!=='undefined') module.exports=VO_LINES; else globalThis.VO_LINES=VO_LINES;})();\n")
