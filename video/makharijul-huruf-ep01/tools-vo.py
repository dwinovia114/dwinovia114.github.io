 ("a3","Ba.","Ba..."),
 ("a3b","Ma.","Ma..."),
 ("a4","Namun, keduanya menghasilkan bunyi yang berbeda.","Namun, keduanya menghasilkan bunyi yang berbeda."),
 ("a5","Mengapa demikian?","Mengapa demikian?"),
 ("b1","Dalam membaca Al Qur'an, mengenal huruf saja belum cukup.","Dalam membaca Al-Qur'an, mengenal huruf saja belum cukup."),
 ("b2","Kita juga perlu mengetahui dari mana setiap huruf berasal, dan bagaimana cara mengucapkannya.","Kita juga perlu mengetahui dari mana setiap huruf berasal dan bagaimana cara mengucapkannya."),
 ("b3","Inilah alasan mengapa kita perlu mempelajari, Makharijul Huruf.","Inilah alasan mengapa kita perlu mempelajari Makharijul Huruf."),
 ("c1","Makharijul Huruf adalah tempat keluarnya bunyi huruf hijaiyah ketika diucapkan.","Makharijul Huruf adalah tempat keluarnya bunyi huruf hijaiyah ketika diucapkan."),
 ("c2","Kata makharij berarti tempat-tempat keluar, sedangkan makhraj berarti satu tempat keluarnya huruf.","Kata makharij berarti tempat-tempat keluar, sedangkan makhraj berarti satu tempat keluarnya huruf."),
 ("c3","Dengan memahami makhraj, kita dapat membedakan pengucapan huruf-huruf yang memiliki bunyi hampir serupa.","Dengan memahami makhraj, kita dapat membedakan pengucapan huruf-huruf yang memiliki bunyi hampir serupa."),
 ("d0","Secara umum, tempat keluarnya huruf hijaiyah dibagi menjadi lima makhraj utama.","Secara umum, tempat keluarnya huruf hijaiyah dibagi menjadi lima makhraj utama."),
 ("d1","Pertama, Al Jauf, yaitu rongga mulut.","Pertama, Al-Jauf, yaitu rongga mulut."),
